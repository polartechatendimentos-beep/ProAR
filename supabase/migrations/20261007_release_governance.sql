-- ProAR Release Governance
-- Estrutura aditiva para promover releases com segurança:
-- Interno -> Homologação -> Canary -> Produção.
-- Não remove nem sobrescreve dados operacionais existentes.

create table if not exists public.proar_release_environments (
  code text primary key check (code in ('internal','homologation','canary','production')),
  name text not null,
  alias text,
  description text,
  customer_facing boolean not null default false,
  requires_approval boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

