"use client";
import { useEffect, useState } from "react";

type Pairing = { base64?: string | null; pairingCode?: string | null; connected?: boolean; error?: string };
type Status = { state?: { instance?: { state?: string }; state?: string }; error?: string };
const stateLabel = (value?: string) => value === "open" ? "Conectado" : value === "connecting" ? "Conectando" : "Desconectado";

export default function WhatsAppPairingPage() {
  const [status, setStatus] = useState<Status | null>(null);
  const [pairing, setPairing] = useState<Pairing | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  async function refresh() {
    try {
      const response = await fetch("/api/whatsapp/evolution", { cache: "no-store" });
      const result = await response.json() as Status;
      if (!response.ok) throw new Error(result.error || "Falha ao consultar conexão");
      setStatus(result);
      const state = result.state?.instance?.state || result.state?.state;
      if (state === "open") setPairing(null);
      setError("");
    } catch (cause) { setError(cause instanceof Error ? cause.message : "Conexão indisponível"); }
  }
  useEffect(() => {
    void refresh();
    const timer = setInterval(() => { if (document.visibilityState === "visible") void refresh(); }, 10000);
    return () => clearInterval(timer);
  }, []);
  async function connect() {
    setBusy(true); setError(""); setPairing(null);
    try {
      const response = await fetch("/api/whatsapp/evolution", { method: "POST", headers: { "Content-Type": "application/json" } });
      const result = await response.json() as Pairing;
      if (!response.ok) throw new Error(result.error || "Não foi possível gerar o QR");
      setPairing(result);
      await refresh();
    } catch (cause) { setError(cause instanceof Error ? cause.message : "Falha no pareamento"); }
    finally { setBusy(false); }
  }
  const state = status?.state?.instance?.state || status?.state?.state;
  return <main style={{ maxWidth: 720, margin: "40px auto", padding: 24, fontFamily: "Arial, sans-serif" }}>
    <h1>WhatsApp — Conectar por QR Code</h1>
    <p>Conexão opcional via Evolution API (WhatsApp Web não oficial). A integração Meta Cloud API permanece separada.</p>
    <p role="status"><strong>Estado:</strong> {stateLabel(state)}</p>
    {error && <p role="alert" style={{ color: "#b91c1c" }}>{error}</p>}
    {pairing?.base64 && <section aria-label="QR Code para pareamento" style={{ margin: "24px 0" }}>
      {/* QR comes from a live Evolution instance, never generated by this page. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={pairing.base64} alt="QR Code temporário da sessão WhatsApp" width={260} height={260} />
      <p>No celular, abra WhatsApp → Aparelhos conectados → Conectar aparelho. Se expirar, solicite outro QR.</p>
    </section>}
    {pairing?.pairingCode && <p>Código de pareamento: <strong>{pairing.pairingCode}</strong></p>}
    <button type="button" onClick={() => void connect()} disabled={busy || state === "open"} style={{ padding: "12px 18px", cursor: "pointer" }}>{busy ? "Solicitando..." : state === "open" ? "WhatsApp conectado" : "Gerar QR Code real"}</button>
    <button type="button" onClick={() => void refresh()} style={{ marginLeft: 12, padding: "12px 18px" }}>Atualizar estado</button>
    <p style={{ color: "#555", fontSize: 13 }}>Apenas administradores com permissão de configurações podem acessar os dados de pareamento. Não há envio automático habilitado nesta etapa.</p>
  </main>;
}
